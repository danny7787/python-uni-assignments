# Variables and Data Types

# Store my personal information
name = "Danny"
age = 41
height = 170.0

# Display my information
print("My name is", name, "I am", age, "years old and", height, "cm tall.")

# Calculate my age in months
age_in_months = age * 12
print("My age in months is", age_in_months)

# Add 10 cm to my height
new_height = height + 10
print("My height with 10 cm added is", new_height, "cm")

# Check if my age is greater than 18
print("Is my age greater than 18?", age > 18)

# Convert my height to an integer
height_as_integer = int(height)
print("My height as an integer is", height_as_integer, "cm")

# Display my age
print("My age is " + str(age))
